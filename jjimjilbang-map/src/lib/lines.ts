// 긴 이름부터 찾아요 ("동대문역사문화공원"을 "동대문"보다 먼저)
const NAMES = Object.keys(STATION_LINES).sort((a, b) => b.length - a.length);

/** "선릉역 8번 출구" → ['2호선', '수인분당선'] */
export function linesOf(stationText: string | null | undefined): Line[] {
  if (!stationText) return [];
  let rest = stationText;
  const out = new Set<Line>();
  for (const n of NAMES) {
    const key = `${n}역`;
    if (rest.includes(key)) {
      STATION_LINES[n].forEach((l) => out.add(l));
      rest = rest.split(key).join(' ');
    }
  }
  return LINE_ORDER.filter((l) => out.has(l));
}
